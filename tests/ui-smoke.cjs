// Run against tests/preview_ui.py only: all credentials and executions are fixtures.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const AxeBuilder = require('@axe-core/playwright').default;
const url = process.env.UI_BASE_URL || 'http://127.0.0.1:8765';
const output = process.env.UI_OUTPUT_DIR || '/tmp/nodeseek-ui';

(async () => {
  fs.mkdirSync(output, {recursive: true});
  const browser = await chromium.launch({headless: true});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, colorScheme: 'light', reducedMotion: 'reduce'});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(url);
    await page.locator('#login').waitFor({state: 'visible'});
    async function audit(label) {
      const result = await new AxeBuilder({page}).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
      assert.deepEqual(result.violations.map(v => ({id: v.id, nodes: v.nodes.map(n => n.target)})), [], `Accessibility: ${label}`);
    }
    await audit('login');
    await page.screenshot({path: path.join(output, 'login.png'), fullPage: true});
    await page.locator('#password').fill('wrong-password');
    await page.locator('#login-form [type=submit]').click();
    await page.locator('#login-error:not([hidden])').waitFor();
    await page.locator('#password').fill('preview-only-password');
    await page.locator('#password-toggle').click();
    assert.equal(await page.locator('#password').getAttribute('type'), 'text');
    await page.locator('#password-toggle').click();
    await page.locator('#login-form [type=submit]').click();
    await page.locator('#dashboard').waitFor({state: 'visible'});
    await page.waitForFunction(() => document.querySelector('#stat-success').textContent !== '0');
    await page.waitForFunction(() => document.querySelector('#scene-layer').dataset.ready === 'true');
    await page.locator('#toast-close').click();
    await page.screenshot({path: path.join(output, 'overview-desktop.png'), fullPage: true});
    await audit('overview light');
    async function view(name) {
      await page.locator(`.primary-nav [data-view=${name}]`).click();
      await page.locator(`#${name}`).waitFor({state: 'visible'});
    }
    await view('schedule');
    await page.locator('#jitter').fill('27');
    await view('account');
    // Reusing the preview server must still exercise an actual credential change.
    const savedAgent = await page.locator('#user-agent').inputValue();
    await page.locator('#user-agent').fill(savedAgent === 'UI fixture browser' ? 'UI fixture browser alternate' : 'UI fixture browser');
    await page.locator('#cookie-form [type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#cookie-save-state').textContent.includes('所有更改已保存'));
    await view('schedule');
    assert.equal(await page.locator('#jitter').inputValue(), '27', 'Saving credentials must preserve the settings draft');
    await page.locator('#settings-form [type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#settings-save-state').textContent.includes('所有更改已保存'));
    await page.locator('#jitter').fill('35');
    await page.locator('#settings-reset').click();
    assert.equal(await page.locator('#jitter').inputValue(), '27');
    await page.screenshot({path: path.join(output, 'settings-desktop.png'), fullPage: true});
    await audit('automation');
    await page.locator('#theme-select').selectOption('dark');
    await view('overview');
    await page.locator('#toast-close').click();
    assert.equal(await page.locator('meta[name=color-scheme]').getAttribute('content'), 'dark');
    await page.screenshot({path: path.join(output, 'overview-dark.png'), fullPage: true});
    await audit('overview dark');
    await page.reload();
    await page.locator('#dashboard').waitFor({state: 'visible'});
    assert.equal(await page.locator('meta[name=color-scheme]').getAttribute('content'), 'dark');
    await view('schedule');
    await page.locator('#theme-select').selectOption('system');
    assert.equal(await page.evaluate(() => localStorage.getItem('nodeseek-theme')), null);
    await view('history');
    await page.locator('#history-filter').selectOption('fail');
    assert.equal(await page.locator('#history-body tr').count(), 3);
    await page.locator('#history-search').fill('no-matching-record');
    await page.locator('#empty-history').waitFor({state: 'visible'});
    await page.locator('#history-search').fill('');
    await page.locator('#history-filter').selectOption('all');
    await page.locator('#next-page').click();
    assert.equal(await page.locator('#page-number').textContent(), '2 / 3');
    await page.locator('#previous-page').click();
    const download = page.waitForEvent('download');
    await page.locator('#export-history').click();
    await (await download).saveAs(path.join(output, 'history.csv'));
    await page.locator('#history-body details').first().locator('summary').click();
    await page.screenshot({path: path.join(output, 'history-desktop.png'), fullPage: true});
    await audit('history');
    await view('account');
    await page.screenshot({path: path.join(output, 'account-desktop.png'), fullPage: true});
    await audit('account');
    const radio = page.locator('[name=account-mode][value=manual]');
    await radio.focus();
    await page.keyboard.press('ArrowRight');
    await page.locator('#browser-pane').waitFor({state: 'visible'});
    await page.keyboard.press('ArrowLeft');
    await page.locator('#manual-pane').waitFor({state: 'visible'});
    await view('overview');
    const count = Number(await page.locator('#history-nav-count').textContent());
    await page.locator('#run').click();
    await page.waitForFunction(n => Number(document.querySelector('#history-nav-count').textContent) > n, count);
    await page.locator('#toast-close').click();
    for (const width of [390, 320, 768, 1024]) {
      await page.setViewportSize({width, height: 900});
      for (const name of ['overview', 'account', 'schedule', 'history']) {
        await view(name);
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${name} overflows at ${width}px`);
        assert.ok(await page.locator('.skip-link').evaluate(el => el === document.activeElement || getComputedStyle(el).clipPath === 'inset(50%)'), 'Unfocused skip link must remain visually hidden');
        await page.screenshot({path: path.join(output, `${name}-${width}.png`), fullPage: true});
      }
    }
    await page.setViewportSize({width: 390, height: 844});
    await audit('mobile history');
    await view('overview');
    await page.route('**/api/status', route => route.abort());
    await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
    await page.locator('#connection-banner').waitFor({state: 'visible'});
    await page.unroute('**/api/status');
    await page.locator('#retry').click();
    await page.locator('#connection-banner').waitFor({state: 'hidden'});
    await view('account');
    await page.locator('#clear-cookie').check();
    await page.locator('#cookie-form [type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#cookie-status').textContent === '尚未连接');
    await view('overview');
    assert.equal(await page.locator('#run').isDisabled(), true);
    await page.locator('#setup-notice').waitFor({state: 'visible'});
    await page.route('**/api/history', route => route.fulfill({json: {items: []}}));
    await page.route('**/api/status', route => route.fulfill({json: {running: false, next_run: null, last_result: null, scheduler_alive: true}}));
    await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
    await page.waitForFunction(() => document.querySelector('#stat-success').textContent === '0');
    await page.screenshot({path: path.join(output, 'overview-empty-mobile.png')});
    await audit('empty overview');
    await view('history');
    await page.locator('#empty-history').waitFor({state: 'visible'});
    assert.equal(await page.locator('#export-history').isDisabled(), true);
    await page.unroute('**/api/history');
    await page.unroute('**/api/status');
    await view('account');
    await page.locator('#cookie').fill('session=preview-fixture');
    await page.locator('#cookie-form [type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#cookie-status').textContent === '已连接');
    await view('schedule');
    await page.locator('#enabled').uncheck();
    await page.locator('#settings-form [type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#settings-save-state').textContent.includes('所有更改已保存'));
    await view('overview');
    assert.equal(await page.locator('#stat-automation').textContent(), '已暂停');
    assert.equal(await page.locator('#run').isDisabled(), false);
    await view('schedule');
    await page.locator('#enabled').check();
    await page.locator('#jitter').fill('15');
    await page.locator('#settings-form [type=submit]').click();
    await page.waitForFunction(() => document.querySelector('#settings-save-state').textContent.includes('所有更改已保存'));
    await page.locator('#logout').click();
    await page.locator('#login').waitFor({state: 'visible'});
    assert.equal(await page.locator('#cookie').inputValue(), '');
    assert.equal(await page.locator('#bark').inputValue(), '');
    assert.deepEqual(errors, []);
    console.log('PASS: login, credentials, preserved drafts, settings, themes, filters, pagination, CSV, keyboard modes, execution, responsive views, reconnect, logout');
    console.log(`Screenshots: ${output}`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
